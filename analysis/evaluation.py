"""
Signal evaluation module.

Computes forward spread returns, information coefficient (IC), and hit rate
for trading signals generated by the statistical arbitrage system.
"""

from __future__ import annotations

import polars as pl
from scipy.stats import spearmanr


def compute_forward_returns(
    signals_df: pl.DataFrame,
    prices: dict[str, pl.DataFrame],
    n_bars: int,
) -> pl.DataFrame:
    """
    Compute forward spread returns for each active signal.

    For each row where signal_binary != 0:
        spread_t  = close_a_t  - hedge_ratio * close_b_t
        spread_tn = close_a_tn - hedge_ratio * close_b_tn
        fwd_return_gross = signal_binary * (spread_tn - spread_t) / abs(spread_t)

    Rows with signal_binary == 0 receive null for fwd_return_gross.

    Args:
        signals_df: DataFrame with schema produced by generate_pair_signals_for_day.
                    Must have columns: timestamp, ticker_a, ticker_b, hedge_ratio,
                    signal_binary.
        prices:     Dict mapping ticker → 15-min OHLCV DataFrame with columns
                    [timestamp, close].
        n_bars:     Number of bars ahead to compute the return.

    Returns:
        signals_df with an additional ``fwd_return_gross: Float64`` column.
        Rows where the forward bar is unavailable also receive null.
    """
    timestamps_sorted: dict[str, list] = {}
    ts_to_idx: dict[str, dict] = {}
    close_arrays: dict[str, list] = {}

    # Pre-process price data per ticker
    for ticker, df in prices.items():
        ts_list = df["timestamp"].to_list()
        close_list = df["close"].to_list()
        idx_map = {ts: i for i, ts in enumerate(ts_list)}
        timestamps_sorted[ticker] = ts_list
        ts_to_idx[ticker] = idx_map
        close_arrays[ticker] = close_list

    fwd_returns: list[float | None] = []

    for row in signals_df.iter_rows(named=True):
        sig = row["signal_binary"]
        if sig == 0:
            fwd_returns.append(None)
            continue

        ticker_a = row["ticker_a"]
        ticker_b = row["ticker_b"]
        hedge_ratio = row["hedge_ratio"]
        ts = row["timestamp"]

        if ticker_a not in ts_to_idx or ticker_b not in ts_to_idx:
            fwd_returns.append(None)
            continue

        idx_a = ts_to_idx[ticker_a].get(ts)
        idx_b = ts_to_idx[ticker_b].get(ts)

        if idx_a is None or idx_b is None:
            fwd_returns.append(None)
            continue

        fwd_idx_a = idx_a + n_bars
        fwd_idx_b = idx_b + n_bars

        closes_a = close_arrays[ticker_a]
        closes_b = close_arrays[ticker_b]

        if fwd_idx_a >= len(closes_a) or fwd_idx_b >= len(closes_b):
            fwd_returns.append(None)
            continue

        close_a_t = closes_a[idx_a]
        close_b_t = closes_b[idx_b]
        close_a_tn = closes_a[fwd_idx_a]
        close_b_tn = closes_b[fwd_idx_b]

        spread_t = close_a_t - hedge_ratio * close_b_t
        spread_tn = close_a_tn - hedge_ratio * close_b_tn

        if spread_t == 0.0:
            fwd_returns.append(None)
            continue

        fwd_return = float(sig) * (spread_tn - spread_t) / abs(spread_t)
        fwd_returns.append(fwd_return)

    return signals_df.with_columns(
        pl.Series("fwd_return_gross", fwd_returns, dtype=pl.Float64)
    )


def compute_net_forward_returns(
    signals_df: pl.DataFrame,
    cost_bps: float = 20.0,
) -> pl.DataFrame:
    """
    Compute net forward returns after deducting round-trip transaction costs.

    fwd_return_net = fwd_return_gross - 4 * (cost_bps / 10_000)

    The factor of 4 accounts for 4 legs in a pairs trade:
    entry leg A, entry leg B, exit leg A, exit leg B.

    Args:
        signals_df: DataFrame with ``fwd_return_gross`` column.
        cost_bps:   One-way cost per leg in basis points. Default 20bps.

    Returns:
        signals_df with an additional ``fwd_return_net: Float64`` column.
    """
    round_trip_cost = 4.0 * (cost_bps / 10_000.0)
    return signals_df.with_columns(
        (pl.col("fwd_return_gross") - round_trip_cost).alias("fwd_return_net")
    )


def compute_ic(
    weighted_signal: pl.Series,
    forward_returns: pl.Series,
) -> float:
    """
    Compute Spearman information coefficient (IC) between weighted signals
    and realized forward returns.

    Null values in either series are excluded before computing correlation.

    Args:
        weighted_signal: Continuous signal series (e.g., signal_weighted).
        forward_returns: Realized forward return series (fwd_return_gross or net).

    Returns:
        Spearman correlation coefficient in [-1, 1], or 0.0 if fewer than 2
        non-null pairs remain.
    """
    df = pl.DataFrame({"ws": weighted_signal, "fr": forward_returns}).drop_nulls()
    if len(df) < 2:
        return 0.0
    corr, _ = spearmanr(df["ws"].to_numpy(), df["fr"].to_numpy())
    return float(corr)


def compute_hit_rate(
    binary_signal: pl.Series,
    forward_returns: pl.Series,
) -> float:
    """
    Compute hit rate: fraction of active signals where sign(fwd_return) == signal.

    Zero signals and null forward returns are excluded.

    Args:
        binary_signal:  Integer series of +1, -1, 0 signals.
        forward_returns: Realized forward return series.

    Returns:
        Hit rate in [0, 1], or 0.0 if no active signals with non-null returns.
    """
    df = pl.DataFrame({"sig": binary_signal, "fr": forward_returns}).filter(
        pl.col("sig") != 0
    ).drop_nulls()

    if len(df) == 0:
        return 0.0

    hits = df.filter(
        (pl.col("fr") > 0) & (pl.col("sig") > 0)
        | (pl.col("fr") < 0) & (pl.col("sig") < 0)
    )
    return float(len(hits)) / float(len(df))


def evaluate_all(
    signals_df: pl.DataFrame,
    prices: dict[str, pl.DataFrame],
    holding_bars_list: list[int],
    cost_bps: float = 20.0,
) -> pl.DataFrame:
    """
    Evaluate signals across multiple holding horizons.

    For each horizon in ``holding_bars_list`` and each trading date:
      1. Compute gross forward returns.
      2. Compute net forward returns.
      3. Compute cross-sectional Spearman IC (gross and net) on weighted signals.
      4. Compute binary signal hit rate.

    Args:
        signals_df:        Full signals DataFrame (all pairs, all timestamps).
                           Must have columns: date, timestamp, ticker_a, ticker_b,
                           hedge_ratio, signal_binary, signal_weighted.
        prices:            Dict mapping ticker → 15-min OHLCV DataFrame with
                           columns [timestamp, close]. Should contain all bars
                           needed to look ahead n_bars beyond the last signal bar.
        holding_bars_list: List of forward-look horizons (in bars).
        cost_bps:          One-way cost per leg in basis points.

    Returns:
        Polars DataFrame with schema:
        [date: Utf8, n_bars: Int64, ic_gross_weighted: Float64,
         ic_net_weighted: Float64, hit_rate_binary: Float64,
         n_observations: Int64]
    """
    dates = signals_df["date"].unique().sort().to_list()
    result_rows: list[dict] = []

    for date in dates:
        day_signals = signals_df.filter(pl.col("date") == date)

        for n_bars in holding_bars_list:
            with_gross = compute_forward_returns(day_signals, prices, n_bars)
            with_net = compute_net_forward_returns(with_gross, cost_bps=cost_bps)

            # Filter to active signals only for IC computation
            active = with_net.filter(pl.col("signal_binary") != 0)
            n_obs = len(active)

            ic_gross = compute_ic(active["signal_weighted"], active["fwd_return_gross"])
            ic_net = compute_ic(active["signal_weighted"], active["fwd_return_net"])
            hit = compute_hit_rate(with_net["signal_binary"], with_net["fwd_return_gross"])

            result_rows.append(
                {
                    "date": date,
                    "n_bars": n_bars,
                    "ic_gross_weighted": ic_gross,
                    "ic_net_weighted": ic_net,
                    "hit_rate_binary": hit,
                    "n_observations": n_obs,
                }
            )

    if not result_rows:
        return pl.DataFrame(
            schema={
                "date": pl.Utf8,
                "n_bars": pl.Int64,
                "ic_gross_weighted": pl.Float64,
                "ic_net_weighted": pl.Float64,
                "hit_rate_binary": pl.Float64,
                "n_observations": pl.Int64,
            }
        )

    return pl.DataFrame(result_rows).with_columns(
        pl.col("n_bars").cast(pl.Int64),
        pl.col("n_observations").cast(pl.Int64),
    )
